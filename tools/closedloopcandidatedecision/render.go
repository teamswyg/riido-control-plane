package main

import (
	"fmt"
	"strings"
)

func renderDoc(m manifest, result verifyResult) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", m.Title)
	fmt.Fprintln(&b, "<!-- Generated by go run ./tools/closedloopcandidatedecision -write-doc. Do not edit by hand. -->")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "Executable SSOT: [`closed-loop-candidate-decision.riido.json`](closed-loop-candidate-decision.riido.json).")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "## Summary")
	fmt.Fprintf(&b, "\n- decisions: `%d`\n\n", result.DecisionCount)
	renderDecisions(&b, m.Decisions)
	renderLoop(&b, m.Loop)
	return b.String()
}

func renderDecisions(b *strings.Builder, decisions []decisionRecord) {
	fmt.Fprintln(b, "## Decisions")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "| Candidate | Disposition | Priority | Owner | Review By | Next Artifact |")
	fmt.Fprintln(b, "| --- | --- | --- | --- | --- | --- |")
	for _, decision := range decisions {
		fmt.Fprintf(b, "| `%s` | `%s` | `%s` | `%s` | `%s` | `%s` |\n",
			decision.CandidateID, decision.Disposition, decision.Priority,
			decision.Owner, decision.ReviewBy, decision.NextArtifact)
	}
	fmt.Fprintln(b)
}
